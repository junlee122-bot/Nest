// 시스템 프롬프트에 넣을 법령 근거 요약 텍스트
export function lawsForPrompt(): string {
  return LAWS.filter((l) => l.articles.length > 0)
    .map((l) => {
      const arts = l.articles.map((a) => `  - ${a.no}: ${a.gist}`).join("\n");
      return `[${l.name} (${l.effectiveDate})] 적용: ${l.scope}\n${arts}`;
    })
    .join("\n\n");
}
