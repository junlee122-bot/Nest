// 시스템 프롬프트에 넣을 룰북 텍스트
export function rulebookForPrompt(): string {
  const riskLabel = { high: "높음", medium: "주의", low: "참고" } as const;
  return RULEBOOK.map(
    (r) =>
      `${r.id}. ${r.title} [위험:${riskLabel[r.risk]}]\n` +
      `   탐지 힌트: ${r.patterns.join(" / ")}\n` +
      `   근거: ${r.basis.join(", ")}\n` +
      `   설명: ${r.explanation}\n` +
      `   대응: ${r.action}\n` +
      `   사례: ${CASE_NOTES[r.id] ?? ""}`
  ).join("\n\n");
}
